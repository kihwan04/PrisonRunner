def replace_paragraph(paragraph, text):
    # Reuse first run formatting rather than losing the retained template typography.
    runs = paragraph.runs
    if runs:
        runs[0].text = text
        for run in runs[1:]:
            run.text = ''
    else:
        paragraph.add_run(text)

